const { execFileSync, execSync } = require('child_process');
const fs = require('fs/promises');
const fsSync = require('fs');
const path = require('path');

const { tools } = require('playwright-core/lib/coreBundle');
const { program } = require('playwright-core/lib/utilsBundle');

const rootDir = path.resolve(__dirname, '..');
const skillsDir = path.join(rootDir, 'skills');

const ENV_NAME_OVERRIDES = {
  'secrets': 'PLAYWRIGHT_MCP_SECRETS_FILE',
  'cdp-header': 'PLAYWRIGHT_MCP_CDP_HEADERS',
  'remote-header': 'PLAYWRIGHT_MCP_REMOTE_HEADERS',
  'no-sandbox': 'PLAYWRIGHT_MCP_SANDBOX=false',
  'no-webmcp': 'PLAYWRIGHT_MCP_WEBMCP=false',
};

const ENV_DESCRIPTION_OVERRIDES = {
  // CLI launches headless unless --headed or PLAYWRIGHT_MCP_HEADLESS=false is set.
  'headless': 'whether to run browser in headless mode, headless by default.',
};

function run(command, options = {}) {
  console.log(`Running: ${command}`);
  execSync(command, { stdio: 'inherit', cwd: rootDir, ...options });
}

async function updateSkills() {
  console.log('\n=== Running playwright-cli install --skills ===\n');
  run('node playwright-cli.js install --skills', {
    env: { ...process.env, NO_UPDATE_NOTIFIER: '1' },
  });

  console.log('\n=== Updating skills folder ===\n');
  const generatedSkillsDir = path.join(rootDir, '.claude', 'skills', 'playwright-cli');
  const targetSkillsDir = path.join(skillsDir, 'playwright-cli');

  try {
    await fs.access(generatedSkillsDir);
    await fs.rm(targetSkillsDir, { recursive: true, force: true });
    await fs.cp(generatedSkillsDir, targetSkillsDir, { recursive: true });
    console.log(`Copied skills from ${generatedSkillsDir} to ${targetSkillsDir}`);

    await fs.rm(generatedSkillsDir, { recursive: true });
    console.log('Cleaned up generated skills directory');
  } catch {
    console.warn('Warning: Generated skills directory not found at', generatedSkillsDir);
  }
}

/**
 * Replaces content between startMarker and endMarker in README.md.
 */
function updateSection(content, startMarker, endMarker, generatedLines) {
  const startMarkerIndex = content.indexOf(startMarker);
  const endMarkerIndex = content.indexOf(endMarker);
  if (startMarkerIndex === -1 || endMarkerIndex === -1)
    throw new Error(`Markers not found in README.md: ${startMarker}`);

  return [
    content.slice(0, startMarkerIndex + startMarker.length),
    '',
    generatedLines.join('\n'),
    '',
    content.slice(endMarkerIndex),
  ].join('\n');
}

/**
 * Resolves upstream config.d.ts matching the pinned playwright-core version.
 */
async function readUpstreamConfigDts() {
  const corePkg = require('playwright-core/package.json');
  const siblingPlaywrightDir = path.join(rootDir, '..', 'playwright');
  const configRelPath = 'packages/playwright-core/src/tools/mcp/config.d.ts';

  let gitHead = corePkg.gitHead;
  if (!gitHead) {
    try {
      gitHead = execFileSync('npm', ['view', `playwright-core@${corePkg.version}`, 'gitHead', '--no-update-notifier'], {
        cwd: rootDir,
        encoding: 'utf-8',
        shell: process.platform === 'win32',
      }).trim();
    } catch {
      gitHead = '';
    }
  }

  if (gitHead && fsSync.existsSync(path.join(siblingPlaywrightDir, '.git'))) {
    try {
      return execFileSync('git', ['-C', siblingPlaywrightDir, 'show', `${gitHead}:${configRelPath}`], {
        encoding: 'utf-8',
      });
    } catch {
    }
  }

  if (gitHead) {
    const url = `https://raw.githubusercontent.com/microsoft/playwright/${gitHead}/${configRelPath}`;
    const response = await fetch(url);
    if (response.ok)
      return await response.text();
    console.warn(`Warning: Failed to fetch ${url} (${response.status})`);
  }

  const localConfigPath = path.join(siblingPlaywrightDir, configRelPath);
  if (fsSync.existsSync(localConfigPath))
    return await fs.readFile(localConfigPath, 'utf-8');

  throw new Error(`Could not resolve ${configRelPath} for playwright-core@${corePkg.version}`);
}

async function updateConfigSection(content) {
  console.log('Updating config schema in README.md...');
  const configContent = await readUpstreamConfigDts();
  const configTypeMatch = configContent.match(/export type Config = (\{[\s\S]*?\n\});/);
  if (!configTypeMatch)
    throw new Error('Config type not found in config.d.ts');

  const startMarker = '<!--- Config generated by scripts/update.js -->';
  const endMarker = '<!--- End of config generated section -->';
  return updateSection(content, startMarker, endMarker, [
    '```typescript',
    configTypeMatch[1].replace(/\r\n/g, '\n'),
    '```',
  ]);
}

function updateEnvSection(content) {
  console.log('Updating environment variables table in README.md...');
  const coreBundlePath = require.resolve('playwright-core/lib/coreBundle');
  const coreBundleSource = fsSync.readFileSync(coreBundlePath, 'utf-8');
  const supportedEnvVars = new Set(coreBundleSource.match(/\bPLAYWRIGHT_MCP_[A-Z0-9_]+\b/g) || []);
  if (!supportedEnvVars.size)
    throw new Error(`No PLAYWRIGHT_MCP_* environment variables found in ${coreBundlePath}`);

  const command = new program.constructor();
  tools.decorateMCPCommand(command, '0.0.0');
  const rows = [];
  for (const option of command.options) {
    const longName = option.long?.replace(/^--/, '');
    if (!longName || longName === 'version' || longName === 'help')
      continue;
    const envName = ENV_NAME_OVERRIDES[longName] ?? `PLAYWRIGHT_MCP_${longName.toUpperCase().replace(/-/g, '_')}`;
    if (!supportedEnvVars.has(envName.split('=')[0]))
      continue;
    const description = ENV_DESCRIPTION_OVERRIDES[longName] ?? option.description.replace(/\s+/g, ' ').trim();
    rows.push({ envName, description });
  }
  rows.sort((a, b) => a.envName.localeCompare(b.envName));

  const table = [
    '| Environment |',
    '|-------------|',
    ...rows.map(row => `| \`${row.envName}\` ${row.description} |`),
  ];

  const startMarker = '<!--- Env generated by scripts/update.js -->';
  const endMarker = '<!--- End of env generated section -->';
  return updateSection(content, startMarker, endMarker, table);
}

async function updateReadme() {
  console.log('\n=== Updating README.md ===\n');
  const readmePath = path.join(rootDir, 'README.md');
  const raw = await fs.readFile(readmePath, 'utf-8');
  const eol = raw.includes('\r\n') ? '\r\n' : '\n';
  let content = raw.replace(/\r\n/g, '\n');
  content = await updateConfigSection(content);
  content = updateEnvSection(content);
  await fs.writeFile(readmePath, content.replace(/\n/g, eol), 'utf-8');
  console.log('Updated README.md');
}

async function main() {
  await updateSkills();
  await updateReadme();
  console.log('\n=== Update complete! ===\n');
}

main().catch(err => {
  console.error('Error:', err);
  process.exit(1);
});
